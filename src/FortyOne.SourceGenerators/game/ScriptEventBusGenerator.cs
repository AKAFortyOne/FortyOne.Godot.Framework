using FortyOne.SourceGenerators.Helpers;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using SourceGenerator.Helpers;
using System.Collections.Immutable;
using System.Text;
using ParsedParameter = FortyOne.SourceGenerators.Helpers.GeneratorHelper.ParsedParameter;

namespace FortyOne.SourceGenerators
{
	[Generator]
	public class ScriptEventBusGenerator : IIncrementalGenerator
	{
		/// <summary>
		/// 
		/// </summary>
		/// <param name="NamespaceName"></param>
		/// <param name="ClassName">信号所在的 class 的名称</param>
		/// <param name="SignalName">信号全称（含EventHandler末尾标识）</param>
		/// <param name="Parameters">参数全称的字符串列表（类型名 参数名）（如：<c>int NewSlot</c>）</param>
		private record SignalInfo(string NamespaceName, string ClassName, string SignalName, ImmutableArray<string> Parameters);
		
		public void Initialize(IncrementalGeneratorInitializationContext context)
		{
			// if (!System.Diagnostics.Debugger.IsAttached)
			// 	System.Diagnostics.Debugger.Launch();
			
			// 粗筛信号数据，得到混有null和SignalInfo的数据集
			var rawSignalInfos = context.SyntaxProvider.CreateSyntaxProvider(
				predicate: (syntaxNode, _) => syntaxNode is DelegateDeclarationSyntax{AttributeLists.Count: >= 1} delegateDeclarationSyntax 
				                              && (delegateDeclarationSyntax.Identifier.Value?.ToString().EndsWith("EventHandler") ?? true),
				transform: (syntaxContext, _) => {
					// 对语义树进行二筛
					// 1. delegate 委托的符号类型必须是 INamedTypeSymbol
					// 2. delegate 委托的特性的名称必须是 Signal
					if (syntaxContext.SemanticModel.GetDeclaredSymbol(syntaxContext.Node) is not INamedTypeSymbol delegateSymbol
					    || !delegateSymbol.GetAttributes().Any(attr => attr.AttributeClass?.Name == "SignalAttribute")) return null;
					
					// 只要能走到这儿，就一定是带有 [Signal] 前缀的信号
					// 基本从这儿开始就可以随便获取想要的数据了
					
					string namespaceName = delegateSymbol.ContainingNamespace.ToDisplayString();
					string className = delegateSymbol.ContainingType.Name;
					string signalFullName = delegateSymbol.Name;
					
					// 过滤方法列表，拿到Invoke的IMethodSymbol
					var members = delegateSymbol.GetMembers();
					IMethodSymbol? invokeMethodSymbol = null;

					foreach (var member in members)
					{
						if (member is not IMethodSymbol{Name: "Invoke"} methodSymbol) continue;
						
						invokeMethodSymbol = methodSymbol;
						break;
					}

					if (invokeMethodSymbol is null) return new SignalInfo(namespaceName, className, signalFullName, ImmutableArray<string>.Empty);

					var parameters = invokeMethodSymbol.Parameters.Select(parameter => parameter.ToDisplayString()).ToImmutableArray();
					return new SignalInfo(namespaceName, className, signalFullName, parameters);
				}
			);

			
			context.RegisterSourceOutput(rawSignalInfos.Collect(), (sourceProductionContext, rawSignalInfosBatch) => {
				// 对 rawSignalInfos 数据进行清洗
				var validSignalInfos = Enumerable.OfType<SignalInfo>(rawSignalInfosBatch).ToImmutableArray();

				// 如果找不到任何信号则抛出警告
				// 要么是使用方真的没有声明任何信号，要么就是过滤器出问题了。
				if (!validSignalInfos.Any())
				{
					GeneratorHelper.ReportDiagnostic(sourceProductionContext,
						"SG001", "No signals found", 
						"No signal delegates were collected",
						DiagnosticSeverity.Warning);
					return;
				}
				// 到这儿，validSignalInfos里面全部都是有效的信号数据了

				
				IndentedStringBuilder sourceCode = new IndentedStringBuilder();
				var groupSignals = validSignalInfos.GroupBy(info => $"{info.NamespaceName}.{info.ClassName}");
				
				foreach (var groupSignal in groupSignals)
				{
					string uniqueHint = $"{groupSignal.First().NamespaceName}.{groupSignal.First().ClassName}_ScriptSignalSubscribe.g.cs";
					BuildEventBus(sourceCode, groupSignal);
					sourceProductionContext.AddSource(uniqueHint, SourceText.From(sourceCode.ToString(),  Encoding.UTF8));
					sourceCode.Clear();
				}
			});
		}

		private static void BuildEventBus(IndentedStringBuilder stringBuilder, IGrouping<string, SignalInfo> groupSignal)
		{
			var namespaceName = groupSignal.First().NamespaceName;
			var className = groupSignal.First().ClassName;
			
			stringBuilder
				.AppendLine("// Auto generated by ScriptEventBusGenerator in FortyOne.SourceGenerators/ScriptEventBusGenerator.cs")
				.AppendLine()
				.AppendLine("using Godot;")
				.AppendLine("using FortyOne.Tools;")
				.AppendLine("using System;")
				.AppendLine("#nullable enable")
				.AppendLine("#pragma warning disable CS0618 // Type or member is obsolete")
				.AppendLine();
			stringBuilder.AppendLine($"namespace {namespaceName}");
			using (stringBuilder.CodeBlock())
			{
				stringBuilder.AppendLine($"public partial class {className}");
				using (stringBuilder.CodeBlock())
				{
					stringBuilder
						.AppendLine($"public static FromFirst<{className}> From({className} sender) => new FromFirst<{className}>(sender);")
						.AppendLine($"public static ToFirst<{className}> To(GodotObject receiver) => new ToFirst<{className}>(null, receiver);")
						.AppendLine();
					
					foreach (SignalInfo info in groupSignal)
					{
						string signalName = info.SignalName.Replace("EventHandler", "");
						var parsedParameters = GeneratorHelper.ProcessParameters(info.Parameters);
						
						stringBuilder.AppendLine($"public struct {signalName}EventArgs({GeneratorHelper.GetParametersList(parsedParameters)}) : IPublishableEventArgs<{className}, {signalName}EventArgs>");
							using (stringBuilder.CodeBlock())
							{
								stringBuilder
									.AppendLine($"public static EventBus<{className}, {signalName}EventArgs>.Descriptor Desc => DescHolder.Value;")
									.AppendLine($"public {className}? Publisher {{ get; private set; }}")
									.AppendLine($"public GodotObject Subscriber {{ get; private set; }} = null!;")
									.AppendLine();

								stringBuilder.AppendLine("private static class DescHolder");
								using (stringBuilder.CodeBlock())
								{
									stringBuilder
										.AppendLine(
											$"public static EventBus<{className}, {signalName}EventArgs>.Descriptor Value {{ get; }} = new EventBus<{className}, {signalName}EventArgs>.Descriptor(");
									using (stringBuilder.Indent())
									{
										stringBuilder.AppendLine($"{className}.SignalName.{signalName},");
										stringBuilder.Append($"Callable.From(static (");
										if (info.Parameters.Length > 0)
										{
											stringBuilder.Append($"{GeneratorHelper.GetParametersList(parsedParameters)}, ");
										}
										stringBuilder.AppendLine($"GodotObject source) => EventBus<{className}, {signalName}EventArgs>.Relay.OnEmitted(source, new {signalName}EventArgs({GeneratorHelper.GetParametersList(parsedParameters, false)})))");
									}
									stringBuilder.AppendLine(");");
								}
								stringBuilder.AppendLine();
								stringBuilder.AppendLine($"{className}? ISubscribableEventArgs<{className}, {signalName}EventArgs>.Publisher");
								using (stringBuilder.CodeBlock())
								{
									stringBuilder
										.AppendLine("get => Publisher;")
										.AppendLine("set => Publisher = value;");
								}
								stringBuilder.AppendLine();

								stringBuilder.AppendLine($"GodotObject ISubscribableEventArgs<{className}, {signalName}EventArgs>.Subscriber");
								using (stringBuilder.CodeBlock())
								{
									stringBuilder
										.AppendLine("get => Subscriber;")
										.AppendLine("set => Subscriber = value;");
								}
								stringBuilder.AppendLine();

								foreach (ParsedParameter parsedParameter in parsedParameters)
								{
									stringBuilder.AppendLine($"public readonly {parsedParameter.TypeName} {GeneratorHelper.FirstToUpper(parsedParameter.ParameterName)} = {parsedParameter.ParameterName};");
								}
							}
							stringBuilder.AppendLine($"public static void Publish({signalName}EventArgs args) => EventBus<{className}, {signalName}EventArgs>.ExecutePublishSingle(null, null, args);");
							stringBuilder.AppendLine();
					}
				}
			}
			stringBuilder.AppendLine();

			stringBuilder.AppendLine($"namespace FortyOne.Tools");
			using (stringBuilder.CodeBlock())
			{
				stringBuilder
					.AppendLine($"using {namespaceName};")
					.AppendLine($"public static class {className}Extensions");
				using (stringBuilder.CodeBlock())
				{
					foreach (SignalInfo info in groupSignal)
					{
						string signalName = info.SignalName.Replace("EventHandler", "");
						stringBuilder
							.AppendLine($"public static EventSubscriptionToken Subscribe(this ToFirst<{className}> chain, Action<{className}.{signalName}EventArgs> callback) => chain.Subscribe<{className}.{signalName}EventArgs>(callback);")
							.AppendLine($"public static EventSubscriptionToken Subscribe(this FromEnd<{className}> chain, Action<{className}.{signalName}EventArgs> callback) => chain.Subscribe<{className}.{signalName}EventArgs>(callback);")
							.AppendLine();
					}
				}
			}
		}
	}
}